macro_rules! register_native_functions {
    ( $( $name:expr => $func:path ),* $(,)? ) => {
        pub fn get_stdlib_functions() -> Vec<(String, hyperion_core::types::function::NativeFn)> {
            vec![
                $( ($name.to_string().to_lowercase(), $func as hyperion_core::types::function::NativeFn) ),*
            ]
        }
    };
}

